#!/usr/bin/env bash
# Assemble the distributable capture skill from the canonical files.
#
# Canonical sources live in spec/, installer/ and tools/. The skill folder
# skills/agent-passport/ must be self-contained, because it gets copied or zipped and
# handed to someone else's coding agent. Rather than keeping two hand-edited
# copies, edit the canonical file and run this.
#
# Also merges spec/resolution.d/*.yaml into spec/resolution.yaml as a
# multi-document YAML file, one document per platform. Read it with
# yaml.safe_load_all, not safe_load.

set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"

refs="skills/agent-passport/references"
mkdir -p "$refs/installer-branches" skills/agent-passport/scripts

# --- resolution map -----------------------------------------------------
{
  echo "# Resolution map: capability x platform."
  echo "# GENERATED. Do not edit this file; edit the canonical per-platform"
  echo "# sources it is built from and rebuild. This header names no path because"
  echo "# the file ships to a repository where those paths do not exist."
  echo "# Multi-document YAML, one document per platform. Use yaml.safe_load_all."
  echo "#"
  echo "# Every platform fact here is dated. A row older than its platform's last"
  echo "# UI change is a bug, and the branch instruction that cites it is wrong."
  for f in spec/resolution.d/*.yaml; do
    [ -e "$f" ] || continue
    echo "---"
    cat "$f"
  done
} > spec/resolution.yaml

# --- skill references ---------------------------------------------------
cp spec/passport-0.1.md      "$refs/spec-schema.md"
cp spec/vocabulary.md        "$refs/vocabulary.md"
cp spec/passport-template.md "$refs/passport-template.md"
cp spec/resolution.yaml      "$refs/resolution.yaml"
cp installer/core.md         "$refs/installer-core.md"
# THE SAME WARN-THEN-SHIP-STALE DEFECT AS THE TOOL LOOP BELOW, AND THIS ONE WAS
# SILENT. Until 2026-09-04 this was a guarded `cp` with no else branch at all:
# no delete, no warning, exit 0. Measured by moving verification/judge-prompt.md
# aside and building: the build printed "built: 7 references, 4 branches", exited
# 0, and shipped the PREVIOUS build's judge prompt inside the distributed skill
# with nothing said. Worse than the tool loop, which at least printed a false
# warning. Found by a critic checking whether the fix below had a twin; it did,
# twenty lines up, and the fix's own comment applied to it verbatim.
if [ -f verification/judge-prompt.md ]; then
  cp verification/judge-prompt.md "$refs/judge-prompt.md"
else
  rm -f "$refs/judge-prompt.md"
  echo "warning: verification/judge-prompt.md not found" >&2
  echo "warning: removed any previous $refs/judge-prompt.md so the skill does not ship a stale judge prompt" >&2
fi

rm -f "$refs/installer-branches"/*.md
for f in installer/branches/*.md; do
  [ -e "$f" ] || continue
  cp "$f" "$refs/installer-branches/"
done

# --- skill scripts ------------------------------------------------------
# The Python tools are canonical in tools/ and tested by tools/run_tests.sh.
# preflight.py travels because the capture skill has to answer "will this
# upload?" offline: validate.py is blind to the site's content rules by
# design, and a capture that cannot check them tells its owner the passport
# is finished and lets the upload box deliver the bad news.
# THE DELETE IN THE else BRANCH IS LOAD-BEARING. Without it this loop printed
# "skill will ship without it" and then shipped the copy from the previous
# build, so the warning was false in the one direction that matters: the skill
# keeps running a tool the canonical tree no longer has. doctor.sh check 5
# compares what is there against what it expects to be there and cannot see a
# file that should not exist at all, so nothing downstream catches it either.
# Same reasoning as the passport-to-page.py delete below: a stale copy inside
# the distributed skill folder is a second implementation nobody calls.
for f in scrub.py validate.py preflight.py; do
  if [ -f "tools/$f" ]; then
    cp "tools/$f" "skills/agent-passport/scripts/$f"
  else
    rm -f "skills/agent-passport/scripts/$f"
    echo "warning: tools/$f not found, skill will ship without it" >&2
    echo "warning: removed any previous skills/agent-passport/scripts/$f so the skill does not ship a stale copy" >&2
  fi
done

# Both resolve the repo layout and the skill layout, so the same file works in
# either place. SKILL.md's last step runs publish.py, so it has to be here: a
# skill folder missing it hands over a passport and no link.
cp scripts/assemble.py skills/agent-passport/scripts/assemble.py
cp scripts/publish.py  skills/agent-passport/scripts/publish.py

# passport-to-page.py no longer travels with the skill. It rendered the local
# standalone page the skill used to hand over, and that page is gone; what
# remains of the script (--write, --dump-parts) only ever runs in this repo,
# against site/index.html and web/tools/parity.mjs. A stale copy inside the
# distributed skill folder would be a second renderer nobody calls, which is the
# shape of drift this repo keeps finding.
rm -f skills/agent-passport/scripts/passport-to-page.py

echo "built: $(ls "$refs" | wc -l | tr -d ' ') references, $(ls "$refs/installer-branches" 2>/dev/null | wc -l | tr -d ' ') branches"
